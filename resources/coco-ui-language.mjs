function agentDir() { return process.env.COCO_CODING_AGENT_DIR || join(process.env.HOME || homedir(), ".coco", "agent"); }
export function uiLocale() {
  try { return JSON.parse(readFileSync(join(agentDir(), "language.json"), "utf8")).locale === "zh-CN" ? "zh-CN" : "en"; }
  catch {
    const value = [process.env.LC_ALL, process.env.LC_MESSAGES, process.env.LANG].find((entry) => typeof entry === "string" && entry.trim() !== "") ?? "";
    return /^(?:zh|cmn)(?:[_-](?:CN|SG|Hans))?(?:[.@]|$)/i.test(value) ? "zh-CN" : "en";
  }
}
function interpolate(value, values) {
  return value.replace(/\{([A-Za-z][A-Za-z0-9]*)\}/g, (match, key) => key in values ? String(values[key]) : match);
}
export function uiText(value, values = {}) {
  if (typeof value !== "string") return value;
  if (uiLocale() !== "zh-CN") return interpolate(value, values);
  const translated = ZH[value] ?? value;
  return interpolate(translated, values)
    .replace(/^Select authentication method for (.+):$/, "选择 $1 的认证方式：")
    .replace(/^Login to (.+)$/, "登录 $1")
    .replace(/^Model Name: (.+)$/, "模型名称：$1")
    .replace(/^Configured (.+)$/, "已配置 $1")
    .replace(/^Thinking level: (.+)$/, "推理级别：$1")
    .replace(/^Model: (.+)$/, "模型：$1")
    .replace(/^Session compacted (.+)$/, "会话已压缩 $1")
    .replace(/^Switched to (.+)$/, "已切换到 $1")
    .replace(/^Output truncated\. Full output: (.+)$/, "输出已截断。完整输出：$1")
    .replace(/^Detected system appearance: (.+)$/, "检测到的系统外观：$1")
    .replace(/^No API key found for (.+)\.$/, "未找到 $1 的 API 密钥。")
    .replace(/^No API key found for (.+)\.\nUse \/login to log into a provider via OAuth or API key\. See:\n([\s\S]+)$/, "未找到 $1 的 API 密钥。\n使用 /login 通过 OAuth 或 API 密钥登录提供商。参见：\n$2")
    .replace(/^Restored (\d+) queued messages? to editor$/, "已将 $1 条排队消息恢复到编辑器")
    .replace(/^Thinking blocks: (hidden|visible)$/, (_, state) => `推理内容：${state === "hidden" ? "已隐藏" : "可见"}`)
    .replace(/^Model refresh timed out; showing cached models\.$/, "模型刷新超时，正在显示缓存模型。")
    .replace(/^Could not refresh (.+); showing cached models\.$/, "无法刷新 $1，正在显示缓存模型。")
    .replace(/^Could not refresh (\d+) model catalogs; showing cached models\.$/, "无法刷新 $1 个模型目录，正在显示缓存模型。")
    .replace(/ login-required/g, " 需要登录")
    .replace(/ • unconfigured/g, " • 未配置")
    .replace(/ ✓ configured/g, " ✓ 已配置");
}
export function uiValue(value) {
  return typeof value === "string" ? uiText(value) : value;
}
